def start(title, subtitle):
    return [P(title, 'title'), P(subtitle, 'sub')]


def sources(story, ids):
    H(story, '参考资料', 2)
    for item in plan['sources']:
        if item['id'] in ids:
            label = html.escape(item['id'] + '  ' + item['title'])
            url = html.escape(item['url'], quote=True)
            story.append(Paragraph(f'<link href="{url}" color="#135DA8">{label}</link>  {html.escape(item["claim"])}。', layout.styles['small']))


