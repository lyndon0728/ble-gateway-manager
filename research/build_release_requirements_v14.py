def add_catalog(s):
    requirements = {int(req['id'].split('-')[1]): req for req in baseline}
    ordered = [key for _, ids in CATALOG for key in ids]
    assert len(ordered) == len(requirements) == 60 and set(ordered) == set(requirements)
    valid_ids = {req['id'] for req in baseline}
    assert all(set(req['dependencies']) <= valid_ids for req in baseline)
    assert Counter(req['priority'] for req in baseline) == {'P0': 41, 'P1': 13, 'P2': 6}
    conditional_p0 = {'OH-052', 'OH-053', 'OH-055'}

    def requirement_row(req):
        key = req['id']
        priority = req['priority'] + (' 条件' if key in conditional_p0 else '')
        desc, check = UPDATES.get(key, (req['description'], req['acceptance']))
        if req['condition'] != '所有首销网关及客户本地部署':
            desc += '\n适用条件  ' + req['condition']
        dependencies = '/'.join(value.removeprefix('OH-') for value in req['dependencies'])
        return [f'{key}  {priority}\n{req["title"]}\n主责  {req["owner_role"]}',
                desc, check + (f'\n依赖  {dependencies}' if dependencies else '')]

    for index, (name, ids) in enumerate(CATALOG, start=1):
        chunks = [ids] if len(ids) <= 10 else [ids[:(len(ids) + 1)//2], ids[(len(ids) + 1)//2:]]
        for part, chunk in enumerate(chunks, start=1):
            suffix = f'  {part}/{len(chunks)}' if len(chunks) > 1 else ''
            page(s, f'需求清单 {index:02d}  {name}{suffix}')
            if index == part == 1:
                body(s, '保留原 60 条 OH 编号与依赖。P0 通用 38 条、条件 3 条，P1 13 条，P2 6 条。依赖栏中的数字均为 OH 编号。')
            table(s, ['编号、阶段与责任', '要求与适用条件', '验收与依赖'],
                  [requirement_row(requirements[key]) for key in chunk], [109, 205, 189])


