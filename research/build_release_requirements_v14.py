class RequirementsPDF(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if isinstance(flowable, Paragraph) and flowable.style.name == 'h1':
            label = flowable.getPlainText()
            self.canv.bookmarkPage(label)
            self.canv.addOutlineEntry(label, label)


def build(filename, story):
    destination = layout.OUT / filename
    RequirementsPDF(str(destination), pagesize=layout.A4, rightMargin=46, leftMargin=46,
                    topMargin=42, bottomMargin=46, title=destination.stem,
                    author='网关产品需求').build(story, onFirstPage=footer, onLaterPages=footer)
    print(f'{destination.name} | {len(layout.PdfReader(destination).pages)} pages')


